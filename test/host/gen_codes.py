#!/usr/bin/env python3
"""
Writes a C header with the codes of all effects of the firmware (in the order of effect.c) and
the codes of their parameters, for test_codes.c. Parses the sources, so the host test needs
neither ESP-IDF nor the effects themselves.

Usage: gen_codes.py MAIN_DIR > codes.h
"""

import os
import re
import sys

main = sys.argv[1]
effects_dir = os.path.join(main, 'effects')

# DESCR_EFFECT_X -> code
descr = {}
params = {}
for f in sorted(os.listdir(effects_dir)):
    text = open(os.path.join(effects_dir, f), encoding='utf-8').read()
    if f.endswith('.h'):
        for name, code in re.findall(r'#define\s+(DESCR_EFFECT_\w+)\s+DECL_EFFECT_\w+\(\s*(\w+)\s*,', text):
            descr[name] = code
    elif f.endswith('.c'):
        for code, body in re.findall(r'EFFECT_PARAMS\(\s*(\w+)\s*,\s*\d+\s*\)\s*=\s*\{(.*?)\};', text, re.S):
            params[code] = [m[0] or 'tempo' for m in re.findall(
                r'DECL_PARAM_\w+\(\s*\w+\s*,\s*"([^"]*)"|(DECL_PARAM_TEMPO)\(', body)]

table = open(os.path.join(main, 'effect.c'), encoding='utf-8').read()
table = table[table.index('const effect_descriptor_t effects[]'):table.index('const size_t effects_count')]
order = re.findall(r'\b(DESCR_EFFECT_\w+)', table)

missing = [n for n in order if n not in descr or descr[n] not in params]
if not order or missing:
    sys.exit('gen_codes.py: could not parse ' + (', '.join(missing) or 'the effect list'))

print('// Generated by gen_codes.py, do not edit')
for n in order:
    code = descr[n]
    print('static const char *const params_%s[] = { %s NULL };' % (code, ''.join('"%s", ' % p for p in params[code])))
print('static const struct { const char *code; const char *const *params; } effect_codes[] = {')
for n in order:
    print('    { "%s", params_%s },' % (descr[n], descr[n]))
print('};')
