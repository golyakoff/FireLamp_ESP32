#!/usr/bin/env python3
"""
Effect peaks: runs every effect of the firmware on a PC and writes main/effect_peaks.h, the
brightest frame of every effect in percent of the full white matrix. The firmware caps the
brightness of every effect by its peak (surface.c), so an effect that never lights the whole
matrix is brighter at the same current limit, and its flashes stay as bright as they are.

Every effect runs on 16x16 and 8x8 for RUN_S seconds with the default parameters, then with every
parameter changed one at a time: all the values of a short range (palettes), MAX_STEPS values of
a long one. Rare events (lightning) get a long run; MARGIN covers what a run did not catch.

Needs gcc, ld and the managed components of the firmware (run `idf.py build` once). Run again when
an effect or a built-in GIF changes: python3 tools/preview/effect_peaks.py
"""

import math
import os
from concurrent.futures import ThreadPoolExecutor

import make_previews as mp

OUT = os.path.join(mp.MAIN, 'effect_peaks.h')
SIZES = ((16, 16), (8, 8))
RUN_S = 120
MAX_STEPS = 6
MARGIN = 1.1
# the parameters that do not change the picture, only its speed
SKIP = {'tempo'}


def values(lo, hi, default):
    if hi - lo < 2 * MAX_STEPS:
        return list(range(lo, hi + 1))
    return sorted({lo, hi, default} | {lo + (hi - lo) * i // (MAX_STEPS - 1) for i in range(MAX_STEPS)})


def runs(code):
    params = [line.split() for line in mp.sim('--params', code).splitlines()]
    sets = [[]]
    for p, lo, hi, default in params:
        if p in SKIP:
            continue
        sets += [[f'{p}={v}'] for v in values(int(lo), int(hi), int(default)) if v != int(default)]
    return [(w, h, s) for w, h in SIZES for s in sets]


def peak(code):
    # per mille of the full white matrix
    return max(int(mp.sim('--peak', code, w, h, mp.FPS, RUN_S * mp.FPS, *s)) for w, h, s in runs(code))


def main():
    mp.build()
    effects = [line.split('\t') for line in mp.sim('--list').splitlines()]
    with ThreadPoolExecutor(os.cpu_count()) as pool:
        peaks = list(pool.map(lambda e: peak(e[0]), effects))

    with open(OUT, 'w') as f:
        f.write('// Generated by tools/preview/effect_peaks.py, do not edit: run it again when an effect\n'
                '// or a built-in GIF changes.\n'
                '// Brightest frame of every effect, percent of the full white matrix, with a margin.\n'
                '// EFFECT_PEAK(code, percent)\n')
        for (code, name), p in zip(effects, peaks):
            pct = max(1, min(100, math.ceil(p * MARGIN / 10)))
            f.write(f'EFFECT_PEAK({code}, {pct})\n')
            print(f'{code:16} {p / 10:5.1f} % -> {pct} %')


if __name__ == '__main__':
    main()
